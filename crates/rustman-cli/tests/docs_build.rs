//! `rustman docs build` end to end: `[docs]` is a known section, the
//! output folder rules and exit codes, and secrets from the store never
//! reaching the site or the terminal (api-docs-generation).

mod common;

use std::fs;
use std::path::Path;
use std::process::Output;

use common::{rustman, write};

const TOKEN: &str = "CANARY-docs-71c4e0";

fn stderr(output: &Output) -> String {
    String::from_utf8_lossy(&output.stderr).into_owned()
}

fn stdout(output: &Output) -> String {
    String::from_utf8_lossy(&output.stdout).into_owned()
}

/// A workspace with a `dev` environment holding the secret `token`, and
/// `docs` under `[docs]`.
fn workspace(docs: &str) -> tempfile::TempDir {
    let dir = tempfile::tempdir().unwrap();
    let root = dir.path();
    write(
        root,
        "rustman.toml",
        &format!(
            "[workspace]\nname = \"Shop\"\nversion = 1\n\n[docs]\ntitle = \"Shop API\"\n{docs}"
        ),
    );
    write(
        root,
        "environments/dev.yaml",
        "variables:\n  base_url: http://localhost:9\nsecrets:\n  - token\n",
    );
    write(root, ".gitignore", ".rustman/\n");
    write(
        root,
        "users/list.rman.yaml",
        "version: 1\nkind: http\nname: List users\nurl: '{{base_url}}/users'\nheaders:\n  - name: Authorization\n    value: Bearer {{token}}\n",
    );
    let stored = rustman(root)
        .args(["secret", "set", "token", "--env", "dev"])
        .write_stdin(format!("{TOKEN}\n"))
        .output()
        .unwrap();
    assert!(stored.status.success(), "{}", stderr(&stored));
    dir
}

fn docs(root: &Path, args: &[&str]) -> Output {
    rustman(root)
        .arg("docs")
        .arg("build")
        .args(args)
        .output()
        .unwrap()
}

fn assert_no_secret(root: &Path, output: &Output) {
    assert!(!stdout(output).contains(TOKEN) && !stderr(output).contains(TOKEN));
    let site = root.join("site");
    if !site.exists() {
        return;
    }
    for entry in walk(&site) {
        let text = String::from_utf8_lossy(&fs::read(&entry).unwrap()).into_owned();
        assert!(!text.contains(TOKEN), "{}", entry.display());
    }
}

fn walk(dir: &Path) -> Vec<std::path::PathBuf> {
    let mut out = Vec::new();
    for entry in fs::read_dir(dir).unwrap() {
        let path = entry.unwrap().path();
        if path.is_dir() {
            out.extend(walk(&path));
        } else {
            out.push(path);
        }
    }
    out
}

#[test]
fn build_writes_the_site_without_warnings() {
    let ws = workspace("");
    let output = docs(ws.path(), &[]);
    assert_eq!(output.status.code(), Some(0), "{}", stderr(&output));
    assert!(
        !stderr(&output).contains("unknown key"),
        "{}",
        stderr(&output)
    );
    assert_eq!(stdout(&output), "wrote 6 files to site/\n");
    let index = fs::read_to_string(ws.path().join("site/index.html")).unwrap();
    assert!(index.contains("<title>Shop API</title>"), "{index}");
    assert_no_secret(ws.path(), &output);
}

#[test]
fn a_foreign_folder_exits_2_and_force_overrides() {
    let ws = workspace("");
    write(ws.path(), "site/notes.txt", "mine");
    let output = docs(ws.path(), &[]);
    assert_eq!(output.status.code(), Some(2));
    assert_eq!(
        stderr(&output),
        "error: site/ is not empty and was not generated by rustman docs; use --force\n"
    );
    let output = docs(ws.path(), &["--force"]);
    assert_eq!(output.status.code(), Some(0), "{}", stderr(&output));
}

#[test]
fn publishing_a_secret_exits_2() {
    let ws = workspace("publish_variables = [\"token\"]\n");
    let output = docs(ws.path(), &["--env", "dev"]);
    assert_eq!(output.status.code(), Some(2));
    assert_eq!(
        stderr(&output),
        "error: token is a secret and cannot be published\n"
    );
    assert_no_secret(ws.path(), &output);
}

#[test]
fn a_leaking_template_exits_1_and_leaves_no_file() {
    let ws = workspace("template_dirs = [\"templates\"]\n");
    write(
        ws.path(),
        "templates/endpoint.html",
        &format!("<p>{TOKEN}</p>\n"),
    );
    let output = docs(ws.path(), &[]);
    assert_eq!(output.status.code(), Some(1));
    assert_eq!(
        stderr(&output),
        "error: secret value found in site/endpoints/users-list.html\n"
    );
    assert!(!ws.path().join("site/endpoints/users-list.html").exists());
    assert_no_secret(ws.path(), &output);
}
